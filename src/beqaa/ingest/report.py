"""Writes docs/DATA_STATUS.md (what is real / partial / mock, row counts, coverage) and docs/MOCK_VS_REAL.md (key model outputs on mock vs real inputs; flipped conclusions).
Regenerated by `python -m beqaa.ingest all`."""
from __future__ import annotations

import os

import numpy as np
import pandas as pd

from .. import allocation, escrow, io, m1_access, m2_need_score as m2
from .common import PROCESSED, ROOT

DOCS = ROOT / "docs"


def _with_mode(mode: str, fn):
    old = os.environ.get("BEQAA_DATA")
    os.environ["BEQAA_DATA"] = mode
    try:
        return fn()
    finally:
        if old is None:
            os.environ.pop("BEQAA_DATA", None)
        else:
            os.environ["BEQAA_DATA"] = old


def _md(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    lines += ["| " + " | ".join("" if (isinstance(v, float) and np.isnan(v)) else str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def status_table() -> pd.DataFrame:
    rows = []
    for name in io.DATASETS:
        d = _with_mode("auto", lambda n=name: io.load_dataset(n))
        b = _with_mode("auto", lambda n=name: io.dataset_badge(n))
        nan_cols = [c for c in d.df.columns if d.df[c].isna().all() and c not in ("url",)]
        rows.append({"dataset": name, "badge": io.BADGES[b], "rows": len(d.df), "all-empty columns": ", ".join(nan_cols) if not d.is_mock else "(mock)",
                     "source_id": ", ".join(sorted(set(d.df.get("source_id", pd.Series(["mock"])).dropna().astype(str))))[:60]})
    return pd.DataFrame(rows)


def coverage() -> pd.DataFrame:
    cad = pd.read_csv(PROCESSED / "cadasters.csv", dtype={"cadaster_id": str})
    n = len(cad)
    pop = pd.read_csv(PROCESSED / "population.csv", dtype={"cadaster_id": str})
    fac = pd.read_csv(PROCESSED / "facilities.csv", dtype={"cadaster_id": str})
    tt = pd.read_csv(PROCESSED / "travel_time.csv", dtype={"cadaster_id": str})
    soil = pd.read_csv(PROCESSED / "soil_sites.csv", dtype={"cadaster_id": str})
    sev = pd.read_csv(PROCESSED / "official_severity.csv")
    vul = pd.read_csv(PROCESSED / "vulnerability.csv", dtype={"cadaster_id": str})
    within30 = tt[tt.minutes <= 30].cadaster_id.nunique()
    d = lambda k: f"{k}/{n} ({k / n:.0%})"
    return pd.DataFrame([
        ("population (LRP + WorldPop + DTM)", d(pop.population_total.notna().sum())),
        ("facility located in the cadaster", d(fac.cadaster_id.nunique())),
        ("a facility within 30 min (modelled travel time)", d(within30)),
        ("travel time (assumed speeds)", d(tt.cadaster_id.nunique())),
        ("soil result at the cadaster", d(soil.cadaster_id.nunique())),
        ("district official severity (JIAF/health)", d(cad.district.isin(set(sev.district[sev.jiaf_severity.notna()])).sum())),
        ("IPC phase 3+ share", d(vul.ipc3plus_share.notna().sum())),
        ("household indicators (VASyR/MSNA district)", d(vul.female_headed_hh_share.notna().sum())),
    ], columns=["layer", "cadasters covered"])


