"""Writes docs/IMPLEMENTATION.md from the model outputs (start_site, unit_costs) so the budget numbers cannot drift from the code. Run after `python -m beqaa.pipeline`."""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from beqaa import start_site as ss  # noqa: E402


def render() -> str:
    r = ss.score()
    cl = ss.clusters(r)
    x = r.set_index("cadaster_name")
    usd = lambda v: f"${v:,.0f}"
    top = r.iloc[0]
    zc = cl[cl.cluster_lead == top.cadaster_name].iloc[0] if (cl.cluster_lead == top.cadaster_name).any() else cl.iloc[0]
    wave2 = [n for n in ("Bouday", "Chmistar") if n in x.index]
    w2 = sum(x.loc[n, "startup_central_usd"] for n in wave2)
    herm = "Hermel" if "Hermel" in x.index else None
    others = cl[cl.cluster_lead != zc.cluster_lead].head(1)
    rows = [
        ("Phase 1: pilot site (months 0-12)", f"{top.cadaster_name} ({top.district}), first on the start-site scorer; no single cadaster is stable under random weights, so the cluster around it is the unit",
         f"{usd(top.startup_central_usd)} start-up ({usd(top.startup_low_usd)}-{usd(top.startup_high_usd)}) at full coverage of 2016 settlement households with filters; plus CHW pay $300 a month",
         "consortium lead (primary-care operator), AUB lab, municipality; LHF window funds; MoPH approves the referral endpoint",
         "referral completion >= 0.40, posts filled >= 0.60, transparent reporting published; baselines set in months 1-3"),
        ("Phase 2: wave 2 (months 6-24)", f"the CNRS-L soil villages {' and '.join(wave2)}" + (f", and {herm}" if herm else ""),
         f"{usd(w2)} for {' + '.join(wave2)}" + (f" (+ {usd(x.loc[herm, 'startup_central_usd'])} for {herm})" if herm else ""),
         "same consortium; AUB lab for Cr(VI) speciation (US price proxy $40-77; no Lebanese price)",
         "pilot KPIs met in phase 1 for two consecutive quarters; Cr(VI) result decides protective action"),
        ("Phase 3: district clusters (years 2-4)", f"the {zc.cluster_lead} cluster ({int(zc.n)} cadasters)" + (f" and the {others.iloc[0].cluster_lead} cluster ({int(others.iloc[0].n)} cadasters)" if len(others) else ""),
         f"{usd(zc.startup_central_usd)}" + (f" + {usd(others.iloc[0].startup_central_usd)}" if len(others) else "") + " start-up at full coverage; filters dominate the cost and scale with the share of households covered",
         "national NGO rung, then the municipal union as capacity reaches 0.40", "capacity >= 0.30 then 0.40 (growth capped at 0.05 a year); referral and posts thresholds held"),
        ("Phase 4: handover (to 2030)", "control of the window moves INGO -> national NGO -> union of municipalities -> MoPH", "no new budget line: the window is administered at the higher rung", "MoPH (standards, referral), municipal union (administration), LHF secretariat (verification)",
         "thresholds met and published; independent spot check; the share of money held by Lebanese organisations rises"),
    ]
    t = ["# Implementation and budget by phase (generated by scripts/make_implementation.py from the model outputs)", "",
         "Funding route: a ring-fenced Beqaa window within the Lebanon Humanitarian Fund (registry F004; proposed). A host-project add-on is an optional cost saving. Costs are start-up costs from sourced unit prices (`data/processed/unit_costs.csv`); sample counts and the share of households covered are assumptions (sliders in the Pilot design section); catalogue filter prices are ex-works and exclude freight; there is no Lebanese Cr(VI) price.", "",
         "| Phase | Where | Budget (central, range) | Who acts | KPIs that unlock the next step |", "|---|---|---|---|---|"]
    t += [f"| {a} | {b} | {c} | {d} | {e} |" for a, b, c, d, e in rows]
    t += ["", "Recurring costs (not in the start-up figures): CHW pay $300 a month per CHW (secondary source), water tests $55 per source (nitrate $25 + chromium $30, AUB), primary-care service $20.03 (K2P/UNICEF 2022). "
          "Everything unsourced stays a slider with a break-even (`docs/ASSUMPTIONS_PILOT.md`); the pilot measures the rest."]
    return "\n".join(t) + "\n"


if __name__ == "__main__":
    (ROOT / "docs" / "IMPLEMENTATION.md").write_text(render())
    print("wrote docs/IMPLEMENTATION.md")
